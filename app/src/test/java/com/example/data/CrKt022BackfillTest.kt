/**
 * CR-KT-022 golden: [HistoryBackfill.repair] replays the Kotlin `event_logs` completion rows
 * (`kind` complete/uncomplete, written by `RpgRepository.completeTask/uncompleteTask`) into the
 * per-task `history` points that pre-1.3 never wrote — exactly as the repair spec pins it:
 *
 *  1. LIFO pairing per task, in event order: an un-tick cancels its completion wherever the days
 *     fall (the live CR-PWA-004 rule); rows with `payloadJson` `{late:true}` are skipped
 *     (`creditYesterday` wrote its own backdated point, RpgEngine.kt:617-667).
 *  2. One point per UTC day for the standing completions (the last one wins): daily
 *     `{date, value, completed:true, isDue:true, repeat}`; todo `{date, value, completed:true}` —
 *     no reward/checklist (never recorded in the event log, never fabricated).
 *  3. A UTC day that already carries a `completed:true` point is never modified (protects
 *     PWA-recorded days; idempotent re-runs); a non-completed same-day point (cron miss) is
 *     merged in place as `logHistory` would.
 *  4. Add-only: nothing is ever deleted or un-marked.
 *
 * Fixture: `fixtures/cr_kt_022/backfill_history.json`, copied unchanged from
 * `shared\fixtures\CR-KT-022\` (generated by `gen_backfill_history.js`, which cuts the real Opti
 * 338d430 code out of app.js at run time and asserts every case against it; TZ=UTC; never edited
 * after ACCEPTED — PROTOCOL P4). Driving mirrors the generator: [SerializationEngine.parseTaskEntity]
 * on `task_before`, the fixture's events in fixture order (the DAO's `ORDER BY timestamp ASC,
 * id ASC`), then every repaired point compared field-for-field through
 * [SerializationEngine.buildTaskHistoryPointJson].
 *
 * The `render[]` pins run the real analytics path ([AnalyticsCalc.sourceEvents] + bucket, the
 * `completed` source group "day", TZ=UTC) over repaired tasks: reward-less repaired points must
 * count exactly like PWA points, and a repaired todo counts via the point alone (the repair never
 * sets `completedAt`).
 */
class CrKt022BackfillTest {

    private val zone: ZoneId = ZoneId.of("UTC")

    private val fixture: JsonObject by lazy {
        val f = listOf("fixtures/cr_kt_022", "../fixtures/cr_kt_022")
            .map { File(it, "backfill_history.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject
    }

    private val cases: List<JsonObject> by lazy {
        fixture.getValue("cases").jsonArray.map { it.jsonObject }
    }

    private fun obj(o: JsonObject, key: String): JsonObject = o.getValue(key).jsonObject

    private fun long(o: JsonObject, key: String): Long = (o[key] as JsonPrimitive).content.toLong()

    private fun strOrNull(o: JsonObject, key: String): String? =
        (o[key] as? JsonPrimitive)?.contentOrNull

    private fun intOrNull(o: JsonObject, key: String): Int? = (o[key] as? JsonPrimitive)?.intOrNull

    private fun doubleOrNull(o: JsonObject, key: String): Double? = (o[key] as? JsonPrimitive)?.doubleOrNull

    private fun boolOrNull(o: JsonObject, key: String): Boolean? =
        (o[key] as? JsonPrimitive)?.let { if (it.contentOrNull == "true") true else if (it.contentOrNull == "false") false else null }

    /** The Kotlin event row [RpgRepository.completeTask]/[RpgRepository.uncompleteTask] wrote. */
    private fun event(o: JsonObject): EventLogEntity = EventLogEntity(
        id = long(o, "id"),
        timestamp = long(o, "timestamp"),
        kind = strOrNull(o, "kind")!!,
        taskType = strOrNull(o, "taskType"),
        taskId = strOrNull(o, "taskId"),
        taskTitle = strOrNull(o, "taskTitle"),
        streak = intOrNull(o, "streak"),
        value = doubleOrNull(o, "value"),
        imported = boolOrNull(o, "imported"),
        payloadJson = strOrNull(o, "payloadJson"),
    )

    /** JS `==` on JSON values: key sets equal, numbers as doubles, everything else exact. */
    private fun jsEqual(a: JsonElement, b: JsonElement): Boolean = when {
        a is JsonObject && b is JsonObject ->
            a.keys == b.keys && a.keys.all { jsEqual(a.getValue(it), b.getValue(it)) }
        a is JsonArray && b is JsonArray -> a.size == b.size && a.indices.all { jsEqual(a[it], b[it]) }
        a is JsonPrimitive && b is JsonPrimitive && !a.isString && !b.isString ->
            if (a.doubleOrNull != null && b.doubleOrNull != null) a.doubleOrNull == b.doubleOrNull
            else a == b
        else -> a == b
    }

    private fun assertHistory(caseName: String, expected: JsonArray, actual: JsonArray) {
        val message = "$caseName\n  expected: ${CanonicalJson.stringify(expected)}\n  actual:   ${CanonicalJson.stringify(actual)}"
        assertTrue("$caseName: point count ${expected.size} != ${actual.size}\n$message", expected.size == actual.size)
        for (i in expected.indices) {
            assertTrue("$caseName: point $i differs\n$message", jsEqual(expected[i], actual[i]))
        }
    }

    @Test
    fun `all 13 cases - the repair reproduces expected_history exactly`() {
        assertEquals(13, cases.size)
        for (c in cases) {
            val name = (c["name"] as JsonPrimitive).content
            val task = SerializationEngine.parseTaskEntity(obj(c, "task_before"))
            val events = c.getValue("events").jsonArray.map { event(it.jsonObject) }

            val repaired = HistoryBackfill.repair(task, events)
            val actual = JsonArray(repaired.map { SerializationEngine.buildTaskHistoryPointJson(it) })
            assertHistory(name, c.getValue("expected_history").jsonArray, actual)
        }
    }

    @Test
    fun `render pins - repaired points count exactly as the PWA analytics counts them`() {
        val rows = fixture.getValue("render").jsonArray.map { it.jsonObject }
        assertEquals(3, rows.size)
        for (r in rows) {
            val name = (r["name"] as JsonPrimitive).content
            val task = SerializationEngine.parseTaskEntity(obj(r, "task"))

            val view = AnView(id = "pin", name = "pin", source = "completed", group = "day", chart = "bar")
            val events = AnalyticsCalc.sourceEvents(view, AnData(tasks = listOf(task)), AnPrefs())
            val bucket = AnalyticsCalc.bucket(events, "day", 0L, 4_102_444_800_000L, emptyList(), zone) as AnBucket.Day
            val actual = bucket.dayMap.entries.sortedBy { it.key }.map { it.key to it.value }

            val expected = r.getValue("expected_completed_by_day").jsonArray.map { e ->
                val o = e.jsonObject
                long(o, "day_ms") to (o["v"] as JsonPrimitive).doubleOrNull!!
            }
            assertEquals("$name: counted days", expected.map { it.first }, actual.map { it.first })
            expected.forEachIndexed { i, (d, v) ->
                assertEquals("$name: value on $d", v, actual[i].second, 0.0)
            }
        }
    }
}
