/**
 * CR-KT-020 golden: `RpgEngine.completeTask`/`uncompleteTask` write the per-task `history` point
 * (daily: `isDue`/`repeat`/`reward`/checklist snapshot; todo: `reward`), the todo `completedAt`,
 * the REALIZED-delta `_gr` and the daily-only `_histCreated` — exactly as the PWA
 * `completeTask`/`logHistory`/`unlogToday`/`uncompleteDaily`/`uncompleteTodo`
 * (Opti afdae43 app.js:2457-2580).
 *
 * Fixture: `fixtures/cr_kt_020/complete_history.json`, copied unchanged from
 * `shared\fixtures\CR-KT-020\` (generated by `gen_complete_history.js`, which cuts the real Opti
 * block out of app.js at runtime; TZ=UTC; never edited after ACCEPTED — PROTOCOL P4).
 *
 * Driving, mirroring the generator: [SerializationEngine.parseTaskEntity] on `task_before`, one
 * engine call with the generator's frozen clocks (`nowMs` = `now_ms` / `now_ms_2`; HLC `now()` =
 * `hlc_base + 1` on completion, `+2` on the un-tick), then [SerializationEngine.buildTaskJson]
 * compared field-for-field (key order-insensitive — key order is not on the wire — with JS number
 * semantics, `1 == 1.0`). `daily_complete_paused` is the fixture's one paused case (the
 * generator's `c.paused`, the value the fixture JSON does not carry).
 *
 * HELD (RE-PWA-021 -> CR-PWA-004; not pinned here, see the last two tests):
 *  - `todo_uncomplete_keeps_point`: the kept `completedAt` (will change: deleted on un-tick);
 *  - `daily_uncomplete_next_day_guard`: the kept `completed:true` point + `_histCreated`
 *    (will change: device-local day test, earlier-day points un-marked).
 */
class CrKt020CompleteHistoryTest {

    private val zone: ZoneId = ZoneId.of("UTC")

    private val cases: List<JsonObject> by lazy {
        val f = listOf("fixtures/cr_kt_020", "../fixtures/cr_kt_020")
            .map { File(it, "complete_history.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject.getValue("cases").jsonArray.map { it.jsonObject }
    }

    private fun case(name: String): JsonObject =
        cases.first { (it["name"] as JsonPrimitive).content == name }

    private fun obj(o: JsonObject, key: String): JsonObject = o.getValue(key).jsonObject

    private fun long(o: JsonObject, key: String): Long = (o[key] as JsonPrimitive).content.toLong()

    private fun isPaused(c: JsonObject): Boolean =
        (c["name"] as JsonPrimitive).content == "daily_complete_paused"

    /** The generator's fixed character: `S.char = {xp:100, gold:50, mp:5, hp:50, maxHp:50, lvl:2}`. */
    private fun char() = CharacterEntity(lvl = 2, xp = 100, gold = 50.0, mp = 5, hp = 50.0, maxHp = 50.0, updatedAt = 0L)

    /** `completeTask` from `task_before`, HLC `hlc_base + 1` (the generator's `now()` first call). */
    private fun complete(c: JsonObject): TaskEntity = RpgEngine.completeTask(
        character = char(),
        task = SerializationEngine.parseTaskEntity(obj(c, "task_before")),
        todayDow = -1, // all fixture dailies are due every day; the generator's isDailyDueToday passes
        paused = isPaused(c),
        nowMs = long(c, "now_ms"),
        now = long(c, "hlc_base") + 1,
        zone = zone,
    ).second

    /** `uncompleteTask` on the live post-complete task, HLC `hlc_base + 2` (second call). */
    private fun uncomplete(c: JsonObject, task: TaskEntity): TaskEntity = RpgEngine.uncompleteTask(
        character = char(),
        task = task,
        paused = isPaused(c),
        nowMs = long(c, "now_ms_2"),
        now = long(c, "hlc_base") + 2,
    ).second

    private fun json(task: TaskEntity): JsonObject = SerializationEngine.buildTaskJson(task)

    /**
     * Kotlin's wire rule for `_gr` (PX-24, pinned by GrKeyTest): a task whose original never
     * carried `_gr` does not gain a `_gr: null` key after a pure-Kotlin un-tick, while the PWA
     * object keeps `_gr: null` from `reverseGrant` (app.js:2533). Both read as "no granted
     * reward" (app.js:2528 `t._gr || {…}`), so the un-tick comparisons normalize the KEY
     * (present-null == absent) — the value itself is asserted on the entity (`gr == null`).
     */
    private fun withNullGr(o: JsonObject): JsonObject =
        if (o.containsKey("_gr")) o else JsonObject(o + mapOf("_gr" to JsonNull))

    /** JS `==` on JSON values: key sets equal, numbers as doubles, everything else exact. */
    private fun jsEqual(a: JsonElement, b: JsonElement): Boolean = when {
        a is JsonObject && b is JsonObject ->
            a.keys == b.keys && a.keys.all { jsEqual(a.getValue(it), b.getValue(it)) }
        a is JsonArray && b is JsonArray -> a.size == b.size && a.indices.all { jsEqual(a[it], b[it]) }
        a is JsonPrimitive && b is JsonPrimitive && !a.isString && !b.isString ->
            if (a.doubleOrNull != null && b.doubleOrNull != null) a.doubleOrNull == b.doubleOrNull
            else a == b
        else -> a == b
    }

    private fun assertJson(caseName: String, expected: JsonObject, actual: JsonObject) {
        val expectedKeys = expected.keys.sorted()
        val actualKeys = actual.keys.sorted()
        val message = "$caseName\n  expected: ${CanonicalJson.stringify(expected)}\n  actual:   ${CanonicalJson.stringify(actual)}"
        assertTrue("$caseName: key sets differ\n$message", expectedKeys == actualKeys)
        val bad = expectedKeys.filter { !jsEqual(expected.getValue(it), actual.getValue(it)) }
        assertTrue("$caseName: keys [${bad.joinToString(" ")}] differ\n$message", bad.isEmpty())
    }

    @Test
    fun `cases 1-6 after_complete - the fixture, every field`() {
        val names = listOf(
            "todo_complete_fresh",
            "daily_complete_fresh",
            "daily_complete_merge_onto_miss",
            "daily_complete_checklist",
            "daily_complete_at_ceiling",
            "daily_complete_paused",
        )
        for (name in names) {
            val c = case(name)
            assertJson(name, obj(c, "after_complete"), json(complete(c)))
        }
    }

    @Test
    fun `un-tick cases 7-10 after_complete - the fixture, every field`() {
        val names = listOf(
            "daily_uncomplete_pop_fresh",
            "daily_uncomplete_keep_merged",
            "todo_uncomplete_keeps_point",
            "daily_uncomplete_next_day_guard",
        )
        for (name in names) {
            val c = case(name)
            assertJson(name, obj(c, "after_complete"), json(complete(c)))
        }
    }

    @Test
    fun `case 7 daily_uncomplete_pop_fresh - the fixture, every field`() {
        val c = case("daily_uncomplete_pop_fresh")
        val undone = uncomplete(c, complete(c))
        // _gr is entity-null; its key is normalized (see [withNullGr]).
        assertNull(undone.gr)
        assertJson(
            "daily_uncomplete_pop_fresh after_uncomplete",
            withNullGr(obj(c, "after_uncomplete")),
            withNullGr(json(undone)),
        )
    }

    @Test
    fun `case 8 daily_uncomplete_keep_merged - the fixture, every field`() {
        val c = case("daily_uncomplete_keep_merged")
        val undone = uncomplete(c, complete(c))
        assertNull(undone.gr)
        assertJson(
            "daily_uncomplete_keep_merged after_uncomplete",
            withNullGr(obj(c, "after_uncomplete")),
            withNullGr(json(undone)),
        )
    }

    @Test
    fun `case 9 todo_uncomplete_keeps_point - every field except the held completedAt`() {
        val c = case("todo_uncomplete_keeps_point")
        val undone = uncomplete(c, complete(c))
        assertNull(undone.gr)
        // [DEFERRED_OPEN_QUESTION] CR-PWA-004 (RE-PWA-021 quirk a): the fixture keeps
        // `completedAt = 1792144800000` because `uncompleteTodo` never deletes it
        // (app.js:2569-2580). Unintended; the fixed PWA un-tick deletes it. NOT asserted.
        val held = setOf("completedAt")
        assertJson(
            "todo_uncomplete_keeps_point after_uncomplete (completedAt held)",
            withNullGr(JsonObject(obj(c, "after_uncomplete").filterKeys { it !in held })),
            withNullGr(JsonObject(json(undone).filterKeys { it !in held })),
        )
    }

    @Test
    fun `case 10 daily_uncomplete_next_day_guard - every field except the held history outcome`() {
        val c = case("daily_uncomplete_next_day_guard")
        val undone = uncomplete(c, complete(c))
        assertNull(undone.gr)
        // [DEFERRED_OPEN_QUESTION] CR-PWA-004 (RE-PWA-021 quirk b): the fixture keeps the old
        // `completed:true` point and `_histCreated: true` because `unlogToday` only touches a
        // point dated the current UTC day (app.js:2538-2540). Unintended; the fixed PWA uses a
        // device-local day test and un-marks earlier-day points. NOT asserted.
        val held = setOf("history", "_histCreated")
        assertJson(
            "daily_uncomplete_next_day_guard after_uncomplete (history/_histCreated held)",
            withNullGr(JsonObject(obj(c, "after_uncomplete").filterKeys { it !in held })),
            withNullGr(JsonObject(json(undone).filterKeys { it !in held })),
        )
    }
}
