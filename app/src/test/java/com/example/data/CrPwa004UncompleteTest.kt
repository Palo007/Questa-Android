import java.io.File
import java.time.ZoneId

/**
 * CR-PWA-004 mirror: `RpgEngine.uncompleteTask`/`unlogToday` retract the whole completion record
 * on an un-tick, exactly as the fixed live PWA (Opti `338d430` — `unlogToday` with no UTC-day
 * test, `uncompleteTodo` deleting `completedAt`):
 *
 *  - a point THIS completion created pops wherever the days fall (next UTC day, across UTC
 *    midnight — the reported UTC+2 regression);
 *  - a merged/foreign point (a cron miss, an imported row) is kept, un-marked (`completed:false`),
 *    the task value restored and the reward dropped — now on later days too;
 *  - a todo un-tick deletes `completedAt` (the analytics todo fallback no longer counts a
 *    reverted todo);
 *  - same-day behavior is unchanged (case 1 stays byte-identical to CR-KT-020's same-day pop).
 *
 * Fixture: `fixtures/cr_pwa_004/untick_fix.json`, copied unchanged from
 * `shared\fixtures\CR-PWA-004\` (generated by `gen_untick_fix.js` from Opti `338d430`, the commit
 * that made CR-PWA-004 live; never edited after ACCEPTED — PROTOCOL P4). Driving mirrors the
 * generator: [SerializationEngine.parseTaskEntity] on `task_before`, `RpgEngine.completeTask`
 * with the frozen clocks (`now_ms`; HLC `now()` = `hlc_base + 1`), `RpgEngine.uncompleteTask`
 * with HLC `+2`, then [SerializationEngine.buildTaskJson] compared field-for-field with JS number
 * semantics. `_gr` is key-normalized (see [withNullGr]), as in the CR-KT-020 golden test.
 */
class CrPwa004UncompleteTest {

    private val zone: ZoneId = ZoneId.of("UTC")

    private val cases: List<JsonObject> by lazy {
        val f = listOf("fixtures/cr_pwa_004", "../fixtures/cr_pwa_004")
            .map { File(it, "untick_fix.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject.getValue("cases").jsonArray.map { it.jsonObject }
    }

    private fun case(name: String): JsonObject =
        cases.first { (it["name"] as JsonPrimitive).content == name }

    private fun obj(o: JsonObject, key: String): JsonObject = o.getValue(key).jsonObject

    private fun long(o: JsonObject, key: String): Long = (o[key] as JsonPrimitive).content.toLong()

    /** The generator's fixed character: `S.char = {xp:100, gold:50, mp:5, hp:50, maxHp:50, lvl:2}`. */
    private fun char() = CharacterEntity(lvl = 2, xp = 100, gold = 50.0, mp = 5, hp = 50.0, maxHp = 50.0, updatedAt = 0L)

    /** `completeTask` from `task_before`, HLC `hlc_base + 1` (the generator's first `now()` call). */
    private fun complete(c: JsonObject): TaskEntity = RpgEngine.completeTask(
        character = char(),
        task = SerializationEngine.parseTaskEntity(obj(c, "task_before")),
        todayDow = -1, // all fixture dailies are due every day; the generator's isDailyDueToday passes
        paused = false,
        nowMs = long(c, "now_ms"),
        now = long(c, "hlc_base") + 1,
        zone = zone,
    ).second

    /** `uncompleteTask` on the live post-complete task, HLC `hlc_base + 2` (second `now()` call). */
    private fun uncomplete(c: JsonObject, task: TaskEntity): TaskEntity = RpgEngine.uncompleteTask(
        character = char(),
        task = task,
        paused = false,
        now = long(c, "hlc_base") + 2,
    ).second

    private fun json(task: TaskEntity): JsonObject = SerializationEngine.buildTaskJson(task)

    /**
     * Kotlin's wire rule for `_gr` (PX-24, pinned by GrKeyTest): a task whose original never
     * carried `_gr` does not gain a `_gr: null` key after a pure-Kotlin un-tick, while the PWA
     * object keeps `_gr: null` from `reverseGrant`. Normalize the KEY (present-null == absent).
     */
    private fun withNullGr(o: JsonObject): JsonObject =
        if (o.containsKey("_gr")) o else JsonObject(o + mapOf("_gr" to JsonNull))

    /** JS `==` on JSON values: key sets equal, numbers as doubles, everything else exact. */
    private fun jsEqual(a: JsonElement, b: JsonElement): Boolean = when {
        a is JsonObject && b is JsonObject ->
            a.keys == b.keys && a.keys.all { jsEqual(a.getValue(it), b.getValue(it)) }
        a is JsonArray && b is JsonArray -> a.size == b.size && a.indices.all { jsEqual(a[it], b[it]) }
        a is JsonPrimitive && b is JsonPrimitive && !a.isString && !b.isString ->
            if (a.doubleOrNull != null && b.doubleOrNull != null) a.doubleOrNull == b.doubleOrNull
            else a == b
        else -> a == b
    }

    private fun assertJson(caseName: String, expected: JsonObject, actual: JsonObject) {
        val expectedKeys = expected.keys.sorted()
        val actualKeys = actual.keys.sorted()
        val message = "$caseName\n  expected: ${CanonicalJson.stringify(expected)}\n  actual:   ${CanonicalJson.stringify(actual)}"
        assertTrue("$caseName: key sets differ\n$message", expectedKeys == actualKeys)
        val bad = expectedKeys.filter { !jsEqual(expected.getValue(it), actual.getValue(it)) }
        assertTrue("$caseName: keys [${bad.joinToString(" ")}] differ\n$message", bad.isEmpty())
    }

    @Test
    fun `all 6 cases after_complete - the fixture, every field`() {
        assertCaseCount()
        for (c in cases) {
            val name = (c["name"] as JsonPrimitive).content
            assertJson("$name after_complete", obj(c, "after_complete"), json(complete(c)))
        }
    }

    @Test
    fun `all 6 cases after_uncomplete - the fixed PWA, every field`() {
        assertCaseCount()
        for (c in cases) {
            val name = (c["name"] as JsonPrimitive).content
            val undone = uncomplete(c, complete(c))
            assertNull("$name: un-tick clears _gr", undone.gr)
            assertJson("$name after_uncomplete", withNullGr(obj(c, "after_uncomplete")), withNullGr(json(undone)))
        }
    }

    private fun assertCaseCount() {
        assertTrue("fixture drift: expected 6 cases, found ${cases.size}", cases.size == 6)
    }
}
