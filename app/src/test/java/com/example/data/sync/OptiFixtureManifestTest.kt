package com.example.data.sync

import kotlinx.serialization.json.*
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.security.MessageDigest

/**
 * WP-8.0 (plans/PARITY_FIX_PLAN.html §5 "WP-8.0 — Reconciliation and Opti
 * fixtures") — tests for `tools/gen_opti_fixtures.mjs` and the fixture sets
 * it writes under `fixtures/opti/` (recursively). Three things per the WP-8.0 contract
 * ("Tests: OptiFixtureManifestTest; determinism; dirty-tree refusal."):
 *
 *  - [manifest_hasExpectedShapeAndGitHash] / [everyManifestSha256MatchesFile]:
 *    static checks against whatever `fixtures/opti/manifest.json` is
 *    currently checked out — these do NOT re-run the generator, so they run
 *    in ordinary CI with no Node/git-to-Opti dependency.
 *  - [regenerating_isByteIdentical] (determinism) and
 *    [dirtyOptiTree_refusesToGenerate] (dirty-tree refusal) DO invoke the
 *    generator (`node tools/gen_opti_fixtures.mjs`) against the real original
 *    PWA checkout at [optiRoot], exactly as the acceptance criteria require
 *    ("2 runs give identical sha256 values"; "a dirty tree exits non-zero").
 *    They `assumeTrue` past (JUnit "skip", not "fail") when Node or the pinned
 *    PWA checkout aren't present on the machine running the test, since those
 *    are host-specific prerequisites this module cannot vendor. The PWA lives
 *    in its own repository, https://github.com/Palo007/Questa.
 */
class OptiFixtureManifestTest {

    companion object {
        // Mirrors tools/gen_opti_fixtures.mjs's TARGET_OPTI_GIT constant.
        const val TARGET_OPTI_GIT = PwaToolchain.TARGET_OPTI_GIT
    }

    /**
     * The original PWA checkout: `$OPTI_ROOT`, else a sibling directory named `Opti`.
     * No longer a hardcoded absolute path under one maintainer's home directory --
     * that resolved for exactly one person on one machine.
     */
    private fun optiRoot(): File? = PwaToolchain.optiRoot(repoRoot())

    private fun repoRoot(): File {
        var dir: File? = File(".").absoluteFile
        var attempts = 0
        while (dir != null && attempts < 8) {
            if (File(dir, "fixtures/opti/manifest.json").exists()) return dir
            if (File(dir, "tools/gen_opti_fixtures.mjs").exists()) return dir
            dir = dir.parentFile
            attempts++
        }
        throw IllegalStateException(
            "Could not locate the repo root (looked for fixtures/opti/manifest.json or " +
                "tools/gen_opti_fixtures.mjs) by walking up from ${File(".").absoluteFile}."
        )
    }

    private fun manifestFile(): File = File(repoRoot(), "fixtures/opti/manifest.json")

    private fun sha256Hex(bytes: ByteArray): String {
        val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
        return digest.joinToString("") { "%02x".format(it) }
    }

    /**
     * Structural shape of manifest.json: opti.gitHash pinned to
     * TARGET_OPTI_GIT, every non-G10 fixture set present (G10 is WP-8.1's
     * live-capture set, generated separately — WP-8.0 never writes it), a
     * frozenNow timestamp, and the 4 TZs plans/parity_audit/01_sync.md's
     * "Golden fixture plan" names for TZ-sensitive sets.
     */
    @Test
    fun manifest_hasExpectedShapeAndGitHash() {
        val manifest = manifestFile()
        assertTrue("fixtures/opti/manifest.json must exist (run tools/gen_opti_fixtures.mjs)", manifest.exists())
        val root = Json.parseToJsonElement(manifest.readText(Charsets.UTF_8)).jsonObject

        val opti = root["opti"]!!.jsonObject
        assertEquals(TARGET_OPTI_GIT, opti["gitHash"]!!.jsonPrimitive.content)
        for (key in listOf("appJsSha256", "syncJsSha256", "indexHtmlSha256")) {
            val v = opti[key]!!.jsonPrimitive.content
            assertEquals("$key must be a 64-hex-char SHA-256 digest", 64, v.length)
        }

        assertTrue("manifest.frozenNow must be present", root["frozenNow"] != null)
        val tzs = root["tzs"]!!.jsonArray.map { it.jsonPrimitive.content }.toSet()
        assertEquals(setOf("UTC", "Europe/Bratislava", "Pacific/Auckland", "America/Los_Angeles"), tzs)

        val files = root["files"]!!.jsonObject
        // G10 is WP-8.1's scratch-account live capture, not WP-8.0's -- see
        // plans/PARITY_FIX_PLAN.html §6.1: "generated by WP-8.0 at 7d5d4f3,
        // except G10, which WP-8.1 captures on the scratch account."
        val expectedSets = setOf("G1", "G2_G3", "G2_G3_core", "G4", "G5", "G6", "G7", "G8", "G9", "G11", "G12", "G13") // G2_G3_core: WP-8.5
        assertEquals(expectedSets, files.keys)
        assertFalse("WP-8.0 must not produce G10 (that's WP-8.1's live capture)", files.containsKey("G10"))

        for ((setName, entry) in files) {
            val fileMap = entry.jsonObject
            assertTrue("fixture set $setName must contain at least one file", fileMap.isNotEmpty())
        }
    }

    /**
     * Every sha256 recorded in manifest.json's `files` section matches the
     * actual on-disk file it names, byte for byte. This is the assertion a
     * downstream WP (8.1 through 8.21, per §6.1's Producer -> Consumer table)
     * relies on to know a fixture hasn't drifted from what the manifest says
     * it should be.
     */
    @Test
    fun everyManifestSha256MatchesFile() {
        val root = repoRoot()
        val manifest = Json.parseToJsonElement(manifestFile().readText(Charsets.UTF_8)).jsonObject
        val files = manifest["files"]!!.jsonObject

        var checked = 0
        for ((setName, entry) in files) {
            for ((relPath, expectedHashEl) in entry.jsonObject) {
                val expectedHash = expectedHashEl.jsonPrimitive.content
                val f = File(root, "fixtures/opti/$setName/$relPath")
                assertTrue("fixture file $f named in manifest.json must exist on disk", f.exists())
                val actualHash = sha256Hex(f.readBytes())
                assertEquals("sha256 mismatch for fixtures/opti/$setName/$relPath", expectedHash, actualHash)
                checked++
            }
        }
        assertTrue("expected to check at least one fixture file's hash", checked > 0)
    }

    /**
     * Determinism (WP-8.0 acceptance bullet: "2 runs give identical sha256
     * values"). Runs the real generator twice against the real Opti
     * checkout and diffs every file's sha256 between the two runs.
     */
    @Test
    fun regenerating_isByteIdentical() {
        val root = repoRoot()
        val generator = File(root, "tools/gen_opti_fixtures.mjs")
        assumeTrue("tools/gen_opti_fixtures.mjs must exist", generator.exists())
        assumeTrue("node must be on PATH", isOnPath("node"))
        assumeTrue("git must be on PATH", isOnPath("git"))
        // Pinned-commit check last: it needs git and node, and it is what the generator itself
        // requires (a checkout at the wrong commit, or none at all, makes it exit non-zero).
        assumeTrue(PwaToolchain.skipReason(root), PwaToolchain.pinnedRevOrNull(root) != null)
        val optiPath = PwaToolchain.optiRoot(root)!!.absolutePath

        fun runGeneratorAndHashManifest(): Map<String, String> {
            val proc = ProcessBuilder("node", generator.absolutePath, "--opti-root", optiPath, "--rev", TARGET_OPTI_GIT)
                .directory(root)
                .redirectErrorStream(true)
                .start()
            val output = proc.inputStream.bufferedReader().readText()
            val exit = proc.waitFor()
            assertEquals("generator run failed:\n$output", 0, exit)

            val manifest = Json.parseToJsonElement(manifestFile().readText(Charsets.UTF_8)).jsonObject
            val out = LinkedHashMap<String, String>()
            for ((setName, entry) in manifest["files"]!!.jsonObject) {
                for ((relPath, hashEl) in entry.jsonObject) {
                    out["$setName/$relPath"] = hashEl.jsonPrimitive.content
                }
            }
            return out
        }

        val run1 = runGeneratorAndHashManifest()
        val run2 = runGeneratorAndHashManifest()

        assertEquals("file sets must be identical across 2 runs", run1.keys, run2.keys)
        val mismatches = run1.keys.filter { run1[it] != run2[it] }
        assertTrue("non-deterministic fixture(s), sha256 differs across 2 runs: $mismatches", mismatches.isEmpty())
    }

    /**
     * Dirty-tree refusal ("a dirty tree exits non-zero"). This does NOT touch
     * the real PWA checkout at all -- it
     * builds a throwaway git repo in a temp dir (small app.js/sync.js/index.html,
     * committed), points the generator's `--opti-root` at THAT repo (the
     * generator has no knowledge of, or dependency on, which path it's given --
     * see `parseArgs`/`assertCleanOptiTree` in tools/gen_opti_fixtures.mjs,
     * which only ever `git -C <optiRoot> ...`), then dirties the temp
     * repo's working tree and confirms the generator refuses (non-zero
     * exit, "dirty" in its output). The temp dir is deleted afterwards;
     * nothing in a real PWA checkout is ever read, written, or
     * `git`-invoked against by this test.
     */
    @Test
    fun dirtyOptiTree_refusesToGenerate() {
        val root = repoRoot()
        val generator = File(root, "tools/gen_opti_fixtures.mjs")
        assumeTrue("tools/gen_opti_fixtures.mjs must exist", generator.exists())
        assumeTrue("node must be on PATH", isOnPath("node"))
        assumeTrue("git must be on PATH", isOnPath("git"))

        val tempRoot = createTempDir("opti-fixture-dirty-tree-")
        try {
            initThrowawayOptiRepo(tempRoot)

            // Sanity: the fresh clone must start clean.
            val preStatus = runGit(tempRoot, "status", "--porcelain")
            assertTrue("throwaway repo must start clean, got:\n$preStatus", preStatus.isBlank())

            // Dirty it: an unstaged, uncommitted edit to app.js.
            File(tempRoot, "app.js").appendText("\n// dirty-tree probe\n")
            val dirtyStatus = runGit(tempRoot, "status", "--porcelain")
            assertTrue("throwaway repo must be dirty after the edit", dirtyStatus.isNotBlank())

            val headRev = runGit(tempRoot, "rev-parse", "HEAD").trim()
            val proc = ProcessBuilder("node", generator.absolutePath, "--opti-root", tempRoot.absolutePath, "--rev", headRev)
                .directory(root)
                .redirectErrorStream(true)
                .start()
            val output = proc.inputStream.bufferedReader().readText()
            val exit = proc.waitFor()
            assertNotEquals("generator must refuse (non-zero exit) against a dirty Opti-shaped tree", 0, exit)
            assertTrue(
                "refusal message should mention the dirty tree:\n$output",
                output.contains("dirty", ignoreCase = true)
            )
        } finally {
            tempRoot.deleteRecursively()
        }
    }

    /**
     * Builds a minimal git repo shaped enough like Opti for
     * `gen_opti_fixtures.mjs`'s dirty-tree check to run against: it only
     * needs `git status --porcelain` and `git rev-parse` to work, which any
     * git repo supports regardless of file contents -- the app.js/sync.js/
     * index.html bodies below are intentionally tiny stand-ins, not real
     * Opti source.
     */
    private fun initThrowawayOptiRepo(dir: File) {
        runGit(dir, "init", "-q")
        runGit(dir, "config", "user.email", "fixture-test@example.com")
        runGit(dir, "config", "user.name", "OptiFixtureManifestTest")
        File(dir, "app.js").writeText("// throwaway app.js stand-in for dirty-tree test\nfunction dayStamp(d){ return 0; }\n")
        File(dir, "sync.js").writeText("// throwaway sync.js stand-in for dirty-tree test\nfunction merge(){ return {}; }\n")
        File(dir, "index.html").writeText("<!doctype html><html><head><style>:root{--pageBg:#000;}</style></head><body></body></html>\n")
        runGit(dir, "add", "-A")
        runGit(dir, "commit", "-q", "-m", "throwaway commit for OptiFixtureManifestTest")
    }

    private fun createTempDir(prefix: String): File {
        val dir = File.createTempFile(prefix, "").apply {
            delete()
            mkdirs()
        }
        return dir
    }

    private fun isOnPath(cmd: String): Boolean = try {
        val proc = ProcessBuilder(cmd, "--version").redirectErrorStream(true).start()
        proc.waitFor()
        true
    } catch (e: Exception) {
        false
    }

    private fun runGit(dir: File, vararg args: String): String {
        val proc = ProcessBuilder(listOf("git") + args).directory(dir).redirectErrorStream(true).start()
        val output = proc.inputStream.bufferedReader().readText()
        proc.waitFor()
        return output
    }
}
