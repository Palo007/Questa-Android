/**
 * CR-KT-023 golden: the bulk "Log N reps" sheet writes the PWA `addReps` history point
 * ([RpgEngine.addReps], Part A) and the one-shot replay ([RepsReplay], Part B) restores the points
 * the pre-fix `addHabitReps` never wrote -- from this device's own `habitReps` rows only.
 *
 * Fixture: `fixtures/cr_kt_023/reps_history.json`, copied unchanged to `shared\fixtures\CR-KT-023\`
 * (generated by `gen_reps_history.js`, which cuts the real Opti 3581f49 `addReps`/`scoreHabit`/
 * `logHistory`/analytics out of app.js at run time and asserts every case; TZ=UTC; never edited
 * after ACCEPTED -- PROTOCOL P4). Points are compared field-for-field through
 * [SerializationEngine.buildTaskHistoryPointJson] with JS `==` on JSON values (key-order-free).
 */
class CrKt023RepsHistoryTest {

    private val zone: ZoneId = ZoneId.of("UTC")

    private val fixture: JsonObject by lazy {
        val f = listOf("fixtures/cr_kt_023", "../fixtures/cr_kt_023")
            .map { File(it, "reps_history.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject
    }

    private fun arr(key: String): List<JsonObject> = fixture.getValue(key).jsonArray.map { it.jsonObject }
    private fun obj(o: JsonObject, key: String): JsonObject = o.getValue(key).jsonObject
    private fun long(o: JsonObject, key: String): Long = (o[key] as JsonPrimitive).content.toLong()
    private fun str(o: JsonObject, key: String): String? = (o[key] as? JsonPrimitive)?.contentOrNull
    private fun int(o: JsonObject, key: String): Int? = (o[key] as? JsonPrimitive)?.intOrNull
    private fun dbl(o: JsonObject, key: String): Double? = (o[key] as? JsonPrimitive)?.doubleOrNull
    private fun bool(o: JsonObject, key: String): Boolean? = (o[key] as? JsonPrimitive)?.booleanOrNull

    /** A Kotlin `event_logs` row as the fixture writes it. */
    private fun event(o: JsonObject): EventLogEntity = EventLogEntity(
        id = long(o, "id"),
        timestamp = long(o, "timestamp"),
        kind = str(o, "kind")!!,
        taskType = str(o, "taskType"),
        taskId = str(o, "taskId"),
        taskTitle = str(o, "taskTitle"),
        direction = int(o, "direction"),
        reps = int(o, "reps"),
        value = dbl(o, "value"),
        dev = str(o, "dev"),
        imported = bool(o, "imported"),
    )

    private fun jsEqual(a: JsonElement, b: JsonElement): Boolean = when {
        a is JsonObject && b is JsonObject ->
            a.keys == b.keys && a.keys.all { jsEqual(a.getValue(it), b.getValue(it)) }
        a is JsonArray && b is JsonArray -> a.size == b.size && a.indices.all { jsEqual(a[it], b[it]) }
        a is JsonPrimitive && b is JsonPrimitive && !a.isString && !b.isString ->
            if (a.doubleOrNull != null && b.doubleOrNull != null) a.doubleOrNull == b.doubleOrNull
            else a == b
        else -> a == b
    }

    private fun assertHistory(name: String, expected: JsonArray, actual: JsonArray) {
        val message = "$name\n  expected: ${CanonicalJson.stringify(expected)}\n  actual:   ${CanonicalJson.stringify(actual)}"
        assertTrue("$name: point count ${expected.size} != ${actual.size}\n$message", expected.size == actual.size)
        for (i in expected.indices) assertTrue("$name: point $i differs\n$message", jsEqual(expected[i], actual[i]))
    }

    @Test
    fun `forward - RpgEngine addReps equals the PWA addReps (history, cUp, cDown, value)`() {
        val cases = arr("forward")
        assertEquals(5, cases.size)
        for (c in cases) {
            val name = str(c, "name")!!
            val task = SerializationEngine.parseTaskEntity(obj(c, "task_before"))
            val out = RpgEngine.addReps(task, int(c, "n")!!, now = 4_242L, atMs = long(c, "at"))
            val exp = obj(c, "expected")
            assertHistory(name, exp.getValue("history").jsonArray, JsonArray(out.history.map { SerializationEngine.buildTaskHistoryPointJson(it) }))
            assertEquals("$name cUp", int(exp, "cUp"), out.cUp)
            assertEquals("$name cDown", int(exp, "cDown"), out.cDown)
            assertEquals("$name value", dbl(exp, "value")!!, out.value, 0.0)
            assertEquals("$name updatedAt is the HLC stamp", 4_242L, out.updatedAt)
        }
    }

    @Test
    fun `replay - all 8 cases reproduce expected_history (the PWA history) exactly`() {
        val cases = arr("replay")
        assertEquals(8, cases.size)
        for (c in cases) {
            val name = str(c, "name")!!
            val task = SerializationEngine.parseTaskEntity(obj(c, "task_before"))
            val myDev = str(c, "my_dev")!!
            val boundary = long(c, "boundary_id")
            val events = c.getValue("events").jsonArray.map { event(it.jsonObject) }
            // The runner: done flag set -> nothing; else the DAO order + the local-origin filter.
            val rows = if (bool(c, "replay_done") == true) emptyList()
            else events.sortedWith(compareBy({ it.timestamp }, { it.id })).filter { RepsReplay.isLocal(it, myDev, boundary) }
            val repaired = RepsReplay.replay(task, rows)
            assertHistory(name, c.getValue("expected_history").jsonArray, JsonArray(repaired.map { SerializationEngine.buildTaskHistoryPointJson(it) }))
            // Add-only on the task: the replay returns a history, the counters stay as the sheet left them.
            assertTrue("$name: no point removed", repaired.size >= task.history.size)
        }
    }

    @Test
    fun `local-origin filter - foreign, imported, synthetic, other kinds and post-boundary rows are never replayed`() {
        val base = EventLogEntity(id = 5, timestamp = 1L, kind = "habitReps", taskId = "t", reps = 3, direction = 1, value = 0.0, dev = "me")
        assertTrue(RepsReplay.isLocal(base, "me", 5))
        assertTrue(!RepsReplay.isLocal(base.copy(dev = "d-pwa"), "me", 5))
        assertTrue(!RepsReplay.isLocal(base.copy(dev = null), "me", 5)) // [DEFERRED_OPEN_QUESTION] pre-Stage-4 rows
        assertTrue(!RepsReplay.isLocal(base.copy(imported = true), "me", 5))
        assertTrue(!RepsReplay.isLocal(base.copy(synthetic = true), "me", 5))
        assertTrue(!RepsReplay.isLocal(base.copy(kind = "habitTap"), "me", 5))
        assertTrue(!RepsReplay.isLocal(base.copy(id = 6), "me", 5))
        assertEquals(-3, RepsReplay.signedReps(base.copy(direction = -1)))
        assertEquals(-3, RepsReplay.signedReps(base.copy(direction = -1, reps = -3))) // a pulled PWA row's signed reps
        assertEquals(3, RepsReplay.signedReps(base))
    }

    @Test
    fun `render pins - the reps metric counts replayed points exactly as the PWA analytics`() {
        val rows = arr("render")
        assertEquals(2, rows.size)
        for (r in rows) {
            val name = str(r, "name")!!
            val tasks = r.getValue("tasks").jsonArray.map { SerializationEngine.parseTaskEntity(it.jsonObject) }
            val metric = AnalyticsCalc.parseMetric(obj(r, "metric"))
            val view = AnView(id = "v", name = "v", source = "metric", group = "day", chart = "bar", metricId = metric.id)
            val data = AnData(tasks = tasks, events = AnalyticsCalc.allEvents(tasks), metrics = listOf(metric))
            val bucket = AnalyticsCalc.bucket(AnalyticsCalc.sourceEvents(view, data, AnPrefs()), "day", 0L, 4_102_444_800_000L, emptyList(), zone) as AnBucket.Day
            val actual = bucket.dayMap.entries.sortedBy { it.key }.map { it.key to it.value }
            val expected = r.getValue("expected_metric_by_day").jsonArray.map { e ->
                val o = e.jsonObject
                long(o, "day_ms") to dbl(o, "v")!!
            }
            assertEquals("$name: days", expected.map { it.first }, actual.map { it.first })
            expected.forEachIndexed { i, (d, v) -> assertEquals("$name: value on $d", v, actual[i].second, 0.0) }
        }
    }
}
