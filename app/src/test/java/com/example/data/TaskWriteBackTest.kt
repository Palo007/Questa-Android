/**
 * CR-KT-017: the editor Save's field-wise write-back, Opti saveTask (b7a94cd app.js ~6880-6900).
 * Golden: fixtures/cr_kt_017/ (generated by running the PWA block in Node; copied unchanged from
 * shared\fixtures\CR-KT-017\).
 */
class TaskWriteBackTest {

    private val cases: List<JsonObject> by lazy {
        val f = listOf("fixtures/cr_kt_017", "../fixtures/cr_kt_017").map { File(it, "writeback_cases.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject.getValue("cases").jsonArray.map { it.jsonObject }
    }

    private fun task(o: JsonObject) = SerializationEngine.parseTaskEntity(o)

    @Test fun `every fixture case - saved task is byte-equal to the PWA write-back`() {
        assertEquals(7, cases.size)
        cases.forEach { c ->
            val name = (c["name"] as JsonPrimitive).content
            val out = TaskWriteBack.apply(
                base = task(c.getValue("base").jsonObject),
                sheet = task(c.getValue("sheet").jsonObject),
                live = task(c.getValue("live").jsonObject),
            )
            assertEquals(name, (c["expected_json"] as JsonPrimitive).content,
                CanonicalJson.stringify(SerializationEngine.buildTaskJson(out)))
        }
    }

    private fun t(vararg cl: ChecklistItem, title: String = "T") =
        TaskEntity(id = "x", type = "todo", title = title, checklist = cl.toList(), createdAt = 1, updatedAt = 1)

    @Test fun `attachments and orderIndex always come from the live row`() {
        val img = Attachment(id = "i1", sha = "a".repeat(64), w = 1, h = 1, bytes = 1, addedAt = 5)
        val base = t()
        val live = t().copy(attachments = listOf(img), orderIndex = 9)
        val out = TaskWriteBack.apply(base, base.copy(title = "New"), live)
        assertEquals(listOf(img), out.attachments)
        assertEquals(9L, out.orderIndex)
        assertEquals("New", out.title)
    }

    @Test fun `a subtask the user deleted stays deleted, a sync-arrived one is appended`() {
        val a = ChecklistItem(id = "a", text = "a", done = false)
        val b = ChecklistItem(id = "b", text = "b", done = false)
        val c = ChecklistItem(id = "c", text = "c", done = false)
        val out = TaskWriteBack.apply(t(a, b), t(a), t(a, b, c))
        assertEquals(listOf("a", "c"), out.checklist.map { it.id })
    }

    @Test fun `a nullable typed field the sheet cleared is removed from the live row`() {
        val base = t().copy(repsPerTap = 5)
        val out = TaskWriteBack.apply(base, base.copy(repsPerTap = null), base.copy(notes = "peer"))
        assertNull(out.repsPerTap)
        assertEquals("peer", out.notes)
    }

    // ---- RE-PWA-018: Opti saveTask id-based touchedAt stamping (b7a94cd app.js:6862-6870) ----

    private fun clock(start: Long = 100L): () -> Long { var n = start; return { n++ } }

    @Test fun `stampTouched - text change, done change and a new subtask are stamped, unchanged ones are not`() {
        val base = t(
            ChecklistItem(id = "a", text = "a", done = false, touchedAt = 7),
            ChecklistItem(id = "b", text = "b", done = false),
            ChecklistItem(id = "c", text = "c", done = false, touchedAt = 3),
        )
        val sheet = t(
            ChecklistItem(id = "a", text = "a2", done = false, touchedAt = 7),
            ChecklistItem(id = "b", text = "b", done = true),
            ChecklistItem(id = "c", text = "c", done = false, touchedAt = 3),
            ChecklistItem(id = "n", text = "new", done = false),
        )
        val out = TaskWriteBack.stampTouched(base, sheet, clock())
        assertEquals(listOf(100L, 101L, 3L, 102L), out.checklist.map { it.touchedAt })
        assertEquals(listOf("a2", "b", "c", "new"), out.checklist.map { it.text })
    }

    @Test fun `stampTouched - a reorder or a moved subtask with the same text and done is not stamped`() {
        val a = ChecklistItem(id = "a", text = "a", done = false)
        val b = ChecklistItem(id = "b", text = "b", done = true)
        val out = TaskWriteBack.stampTouched(t(a, b), t(b, a), clock())
        assertEquals(listOf<Long?>(null, null), out.checklist.map { it.touchedAt })
    }

    @Test fun `stampTouched - an empty id is backfilled and the item counts as new`() {
        val base = t(ChecklistItem(id = "", text = "x", done = false))
        val out = TaskWriteBack.stampTouched(base, t(ChecklistItem(id = "", text = "x", done = false)), clock())
        val c = out.checklist.single()
        assertEquals(true, c.id.isNotEmpty())
        assertEquals(100L, c.touchedAt)
    }

    @Test fun `stampTouched - extraJson and other fields survive, nothing changed returns the same sheet`() {
        val a = ChecklistItem(id = "a", text = "a", done = false, extraJson = "{\"foo\":1}")
        val out = TaskWriteBack.stampTouched(t(a), t(a.copy(done = true)), clock())
        assertEquals(a.copy(done = true, touchedAt = 100L), out.checklist.single())
        val same = t(a)
        assertEquals(same, TaskWriteBack.stampTouched(t(a), same, clock()))
    }

    @Test fun `stampTouched then apply - the stamped subtask reaches the saved row`() {
        val a = ChecklistItem(id = "a", text = "a", done = false)
        val base = t(a)
        val sheet = TaskWriteBack.stampTouched(base, t(a.copy(text = "a2")), clock(500))
        val out = TaskWriteBack.apply(base, sheet, base.copy(notes = "peer"))
        assertEquals(500L, out.checklist.single().touchedAt)
        assertEquals("peer", out.notes)
    }
}
