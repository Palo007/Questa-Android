/**
 * CR-KT-016: the task editor's Save writes Opti saveTask's `edit` event (027e371 app.js:6957-6982)
 * and a new task writes `{kind:'create', ...}`. Golden: fixtures/cr_kt_016/ (generated by running
 * the PWA code in Node; copied unchanged from shared\fixtures\CR-KT-016\).
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class CrKt016EditEventTest {

    private val fx: JsonObject by lazy {
        val f = listOf("fixtures/cr_kt_016", "../fixtures/cr_kt_016").map { File(it, "edit_events.json") }.first { it.exists() }
        Json.parseToJsonElement(f.readText(Charsets.UTF_8)).jsonObject
    }
    private val cases by lazy { fx.getValue("edit_cases").jsonArray.map { it.jsonObject } }
    private fun case(name: String) = cases.first { it.str("name") == name }

    private fun JsonObject.str(k: String) = (this[k] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content

    private fun taskOf(o: JsonObject) = TaskEntity(
        id = o.str("id")!!, type = o.str("type")!!, title = o.str("title")!!,
        notes = o.str("notes") ?: "", difficulty = o.str("difficulty") ?: "easy",
        checklist = (o["checklist"] as? JsonArray)?.map { c ->
            val i = c.jsonObject
            ChecklistItem(id = i.str("id")!!, text = i.str("text") ?: "", done = (i["done"] as? JsonPrimitive)?.booleanOrNull == true)
        } ?: emptyList(),
        repeat = (o["repeat"] as? JsonArray)?.map { it.jsonPrimitive.boolean },
        reminders = (o["reminders"] as? JsonArray)?.let { Converters().toReminderSpecList(it.toString()) },
        value = (o["value"] as? JsonPrimitive)?.double ?: 0.0,
        cUp = (o["cUp"] as? JsonPrimitive)?.int ?: 0,
        cDown = (o["cDown"] as? JsonPrimitive)?.int ?: 0,
        createdAt = 1L, updatedAt = 1L,
    )

    private val stubChar = CharacterEntity(xp = 0, gold = 0.0, mp = 0, hp = 50.0, maxHp = 50.0, lvl = 1, updatedAt = 1L)

    /** Kotlin's event for one fixture case, with the fixture's ts/uid/dev; null = no event. */
    private fun kotlinEvent(c: JsonObject): Pair<EventLogEntity?, TaskEntity> {
        val orig = taskOf(c.getValue("orig").jsonObject)
        val edit = taskOf(c.getValue("edit").jsonObject)
        val att = c.getValue("attachments").jsonObject.let { AttachmentDelta(it.getValue("added").jsonPrimitive.int, it.getValue("removed").jsonPrimitive.int) }
        val up = c.getValue("upDelta").jsonPrimitive.int
        val down = c.getValue("downDelta").jsonPrimitive.int
        var after = edit
        val counter = if (up != 0 || down != 0) {
            val (_, t, r) = RpgEngine.adjustHabitCounters(stubChar, edit, edit.cUp, edit.cDown, 2L, upDelta = up, downDelta = down)
            after = t; r
        } else null
        val payload = TaskEditEvent.payload(TaskEditEvent.changes(orig, edit, att, counterChanged = counter != null), counter)
            ?: return null to after
        val fe = c["event"]!!.jsonObject
        return EventLogEntity(
            timestamp = fe.getValue("ts").jsonPrimitive.long, uid = fe.str("uid"), dev = fe.str("dev"),
            kind = "edit", taskType = edit.type, taskId = edit.id, taskTitle = edit.title, payloadJson = payload,
        ) to after
    }

    @Test fun `every fixture edit case - same bytes as the PWA`() {
        cases.forEach { c ->
            val (e, _) = kotlinEvent(c)
            val want = c.str("event_json")
            if (want == null) assertNull(c.str("name"), e)
            else assertEquals(c.str("name"), want, CanonicalJson.stringify(EventSyncEngine.buildEventPushJson(e!!)))
        }
    }

    @Test fun `counter cases - habit value after the loops matches the PWA`() {
        listOf("counter_up_and_down", "counter_reverse", "all_fields_order").forEach { n ->
            val c = case(n)
            assertEquals(n, c.getValue("valueAfter").jsonPrimitive.double, kotlinEvent(c).second.value, 1e-12)
        }
    }

    @Test fun `every fixture edit case - feed lines match the PWA renderer`() {
        cases.filter { it.str("event_json") != null }.forEach { c ->
            val e = kotlinEvent(c).first!!
            val lines = listOf("Edited ${e.taskTitle}" + EditChangeSummary.text(e.payloadJson).let { if (it.isEmpty()) "" else " · $it" }) +
                EditChangeSummary.details(e.payloadJson).map { it.plain }
            assertEquals(c.str("name"), c.getValue("feed_lines").jsonArray.map { it.jsonPrimitive.content }, lines)
        }
    }

    @Test fun `no change gives no payload`() {
        val c = case("no_change_no_event")
        assertTrue(TaskEditEvent.changes(taskOf(c.getValue("orig").jsonObject), taskOf(c.getValue("edit").jsonObject)).isEmpty())
        assertNull(TaskEditEvent.payload(emptyList(), null))
    }

    // ---- ViewModel + Room paths ----

    private lateinit var db: AppDatabase
    private lateinit var repository: RpgRepository
    private lateinit var viewModel: MainViewModel

    @Before
    fun setUp() {
        AppBootQuiesce.quiesce()
        Dispatchers.setMain(UnconfinedTestDispatcher())
        val context = ApplicationProvider.getApplicationContext<Context>()
        val same = Executor { it.run() }
        db = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .allowMainThreadQueries().setQueryExecutor(same).setTransactionExecutor(same).build()
        val store = SyncDataStore(context)
        repository = RpgRepository(
            db.characterDao(), db.taskDao(), db.rewardDao(), db.eventLogDao(),
            db.tagDao(), db.deviceDao(), db.charHistoryDao(), db.tombstoneDao(),
            db.customViewDao(), db.snapshotExtrasDao(), db.metricsExtrasDao(),
            store, database = db
        )
        viewModel = MainViewModel(repository, SyncManager(context, repository, store), store, processLifecycle = null)
    }

    @After
    fun tearDown() {
        db.close()
        viewModel.viewModelScope.cancel()
        Dispatchers.resetMain()
        AppBootQuiesce.quiesce()
    }

    private fun logs() = runBlocking { db.eventLogDao().getLogsInRangeSync(Long.MIN_VALUE, Long.MAX_VALUE) }

    private fun awaitAssert(block: () -> Unit) {
        val end = System.currentTimeMillis() + 5_000
        while (true) {
            try { block(); return } catch (e: Throwable) {
                if (System.currentTimeMillis() > end) throw e
                Thread.sleep(20)
            }
        }
    }

    /** The stored event as it goes on the wire, with the fixture's ts/uid/dev swapped in. */
    private fun wireWith(e: EventLogEntity, fe: JsonObject) = CanonicalJson.stringify(EventSyncEngine.buildEventPushJson(
        e.copy(timestamp = fe.getValue("ts").jsonPrimitive.long, uid = fe.str("uid"), dev = fe.str("dev"))))

    @Test fun `editor save writes one edit event - all fields, attachments and counter in one`() {
        val c = case("all_fields_order")
        val orig = taskOf(c.getValue("orig").jsonObject)
        val edit = taskOf(c.getValue("edit").jsonObject)
        runBlocking { db.taskDao().insertTask(orig); repository.insertCharacter(stubChar) }
        viewModel.saveEditedTask(edit, AttachmentDelta(1, 0), base = orig, editedCUp = edit.cUp, editedCDown = edit.cDown)
        awaitAssert {
            val e = logs().single { it.kind == "edit" }
            assertEquals(c.str("event_json"), wireWith(e, c["event"]!!.jsonObject))
        }
        assertEquals(1, logs().count { it.kind == "edit" })
        val stored = runBlocking { db.taskDao().getTaskByIdSync(orig.id) }!!
        assertEquals(1, stored.cUp)
        assertEquals(c.getValue("valueAfter").jsonPrimitive.double, stored.value, 1e-12)
    }

    @Test fun `editor save of a habit counter only writes one edit event with the counter object`() {
        val c = case("counter_up_and_down")
        val orig = taskOf(c.getValue("orig").jsonObject)
        val edit = taskOf(c.getValue("edit").jsonObject)
        runBlocking { db.taskDao().insertTask(orig); repository.insertCharacter(stubChar) }
        viewModel.saveEditedTask(edit, base = orig, editedCUp = edit.cUp, editedCDown = edit.cDown)
        awaitAssert { assertEquals(c.str("event_json"), wireWith(logs().single { it.kind == "edit" }, c["event"]!!.jsonObject)) }
    }

    @Test fun `editor save with no change writes no event`() {
        val c = case("no_change_no_event")
        val orig = taskOf(c.getValue("orig").jsonObject)
        runBlocking { db.taskDao().insertTask(orig) }
        viewModel.saveEditedTask(orig.copy(), base = orig)
        awaitAssert { assertTrue(runBlocking { db.taskDao().getTaskByIdSync(orig.id) }!!.updatedAt > 1L) }
        Thread.sleep(100)
        assertTrue(logs().none { it.kind == "edit" })
    }

    @Test fun `editor save without a base diffs against the stored row`() {
        val c = case("title_and_notes")
        val orig = taskOf(c.getValue("orig").jsonObject)
        runBlocking { db.taskDao().insertTask(orig) }
        viewModel.saveEditedTask(taskOf(c.getValue("edit").jsonObject))
        awaitAssert { assertEquals(c.str("event_json"), wireWith(logs().single { it.kind == "edit" }, c["event"]!!.jsonObject)) }
    }

    @Test fun `new task writes the create event`() {
        val cc = fx.getValue("create_case").jsonObject
        val fe = cc.getValue("event").jsonObject
        viewModel.createTask(type = "todo", title = "New task")
        awaitAssert {
            val e = logs().single { it.kind == "create" }
            val stored = runBlocking { db.taskDao().getTaskByIdSync(e.taskId!!) }!!
            // the fixture's task id is "n1"; swap ours in to compare the rest byte for byte
            val want = cc.str("event_json")!!.replace("\"taskId\":\"n1\"", "\"taskId\":\"${stored.id}\"")
            assertEquals(want, wireWith(e, fe))
            assertEquals(cc.getValue("feed_lines").jsonArray[0].jsonPrimitive.content, "Created ${e.taskType} ${e.taskTitle}")
        }
    }
}
