#!/usr/bin/env node
// tools/gen_opti_fixtures.mjs
//
// Golden-fixture generator: byte-exact vectors produced by the LIVE, pinned original PWA
// code, consumed by Kotlin JUnit.
//
// Goal: byte-exact vectors produced by the pinned original Questa web app
// (https://github.com/Palo007/Questa at TARGET_OPTI_GIT), consumed by Kotlin JUnit.
//
// How it works
// ------------
// Opti's own app.js/sync.js are NOT ES modules and touch DOM/IDB/localStorage
// at load time, so they cannot be `import`ed directly into Node. This
// generator instead reads the two files' TEXT straight out of git's object
// database at the pinned commit (`git show <rev>:<path>`, a read-only blob
// read -- it NEVER touches Opti's working tree, never checks it out, never
// writes to the Opti repo), locates the specific functions each fixture set
// needs by ANCHOR (a regex on the declaration line, exactly the technique
// Opti's own tests/_extract.js uses for the same reason), and evaluates just
// those functions in a `vm` sandbox alongside a handful of documented stand-in
// globals (a capturing logEvent(), a fixed syncDeviceId(), etc. -- each one
// commented at its call site below). The MERGE/EVENT ALGORITHMS THEMSELVES ARE
// NEVER REWRITTEN: every byte of application logic under test is the real
// Opti source at the pinned commit.
//
// Determinism: Date.now()/`new Date()` are pinned process-wide via a FixedDate
// subclass; every entity id/uid used in synthetic inputs is a hardcoded
// literal (no Math.random). TZ-sensitive sets (G9, G12) are generated by
// re-spawning this same script as a child process once per TZ, because V8
// caches a process's local-time zone at first use -- only a fresh process
// reliably picks up a new `process.env.TZ`.
//
// Usage:
//   node tools/gen_opti_fixtures.mjs [--opti-root <dir>] [--rev <sha>]
//   node tools/gen_opti_fixtures.mjs --emit-set <G-set> --tz <IANA-tz>   (internal, child-process mode)
//
// Refuses (exit 1) when:
//   - `git -C <optiRoot> status --porcelain` is non-empty (dirty Opti tree)
//   - the pinned rev cannot be read from <optiRoot>'s object database
