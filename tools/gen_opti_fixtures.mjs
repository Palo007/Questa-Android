// G2/G3: merge()/_mergeInner() and everything it calls that lives in the same
// region of sync.js (stableClone/stableStringify, mergeCollection,
// mergeDevices, mergeDayArray, the char-accumulate/skew-diag helpers,
// dayStampOf/doneDayOf/_isCronEchoReset/normalizeDailyResets -- also reused
// verbatim by G9 below). logEvent (app.js) and dayStamp (app.js) are the only
// two functions merge()/_mergeInner() calls that live OUTSIDE this span.
// WP-8.5: `deviceStub` adds a syncDeviceId() that returns merge()'s own localDeviceId
// (globalThis.__lDev), as production does (sync.js:2453 passes syncDeviceId() as
// localDeviceId). Without it mergeCollection's `_localDev` is null (sync.js:1328), so the
// cAbs watermark path and task-event winnerDev never run. Only the G2_G3_core set uses it;
// G2_G3 keeps its original no-stub vectors byte for byte.
function buildMergeSandbox(appJs, syncJs, deviceStub) {
  const ctx = vm.createContext({ console });
  installFixedDate(ctx, FIXED_NOW_MS);
  const maxSkewConst = extractLine(syncJs, /^const MAX_FUTURE_SKEW_MS =/, 'MAX_FUTURE_SKEW_MS');
  const core = extractBlock(syncJs, /^function stableClone\(/, /^function _mergeInner\(/, 'merge-core');
  const mergeFn = extractFn(syncJs, /^function merge\(/, 'merge');
  const dayStamp = extractFn(appJs, /^function dayStamp\(/, 'dayStamp');
  const src = [
    maxSkewConst,
    dayStamp,
    core,
    mergeFn,
    // Real app.js now()/HLC issuance (app.js ~118): trivial monotonic-clock
    // wrapper, reproduced verbatim rather than extracted since it closes over
    // module state (`S`, lastIssued) merge() does not otherwise need touched.
    'var __lastIssued = 0;',
    'function now(){ var p = Date.now(); __lastIssued = Math.max(p, __lastIssued + 1); return __lastIssued; }',
    // logEvent (app.js) normally mutates S.history/S.__seq and calls save();
    // merge()/_mergeInner() only care that logEvent(ev) is CALLED with a given
    // payload (spec: "captured logEvent calls"), so this capture-only stand-in
    // is the sink under test, not app.js's own persistence side effects.
    'globalThis.__capturedEvents = [];',
    'function logEvent(ev){ globalThis.__capturedEvents.push(ev); }',
    'function save(){ /* no-op: persistence is outside merge()\'s contract */ }',
    // sync.js:2353 -- per-round de-dupe set for the conflict-event throttle,
    // reset once per merge() call in the real app's syncNow() loop. A fresh
    // Set per sandbox instance mirrors that (each fixture case builds its own
    // sandbox), so throttling never leaks across cases.
    'var _conflictLogThrottle = new Set();',
  ].concat(deviceStub ? ['function syncDeviceId(){ return globalThis.__lDev; }'] : []).join('\n\n');
  vm.runInContext(src, ctx);
  return ctx;
}

