function parseArgs(argv) {
  const out = { optiRoot: process.env.OPTI_ROOT || DEFAULT_OPTI_ROOT, rev: process.env.OPTI_REV || TARGET_OPTI_GIT };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--opti-root') out.optiRoot = argv[++i];
    else if (a === '--rev') out.rev = argv[++i];
    else if (a === '--emit-set') out.emitSet = argv[++i];
    else if (a === '--tz') out.tz = argv[++i];
  }
  return out;
}

